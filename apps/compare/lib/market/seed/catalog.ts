/**
 * Demo catalog: invented sets and printings used when no database is configured.
 * Ids are `<setcode>-<number>` for a number's first printing, with `-f` (foil),
 * `-tf` (textured foil) or `-p` (parallel) for further printings of the same number.
 */
import type { CardFinish, CardSet, MarketCard } from "../types";

type SeedSetCode = "NTG01" | "NTG02" | "NTG03" | "NTG04" | "NTPR";

