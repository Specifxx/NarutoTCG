/** A number's first printing; `finish` defaults to non-foil. */
type Printing = Omit<MarketCard, "id" | "set" | "setCode" | "number" | "finish"> & { finish?: CardFinish };

/** A further printing of the same number: a parallel (any finish) or a premium-finish copy. */
type Variant = { rarity: "parallel"; finish: CardFinish } | { finish: "foil" | "textured-foil" };

function variantSuffix(variant: Variant): string {
  if ("rarity" in variant) return "p";
  return variant.finish === "foil" ? "f" : "tf";
}

function printings(setCode: SeedSetCode, number: string, first: Printing, variants: Variant[] = []): MarketCard[] {
  const set = SEED_SETS.find((s) => s.code === setCode);
  if (!set) throw new Error(`Seed set ${setCode} is not defined`);
  const base: MarketCard = {
    ...first,
    id: `${setCode}-${number}`.toLowerCase(),
    set: set.name,
    setCode,
    number,
    finish: first.finish ?? "non-foil",
  };
  return [
    base,
    ...variants.map((variant) => ({
      ...base,
      id: `${base.id}-${variantSuffix(variant)}`,
      finish: variant.finish,
      rarity: "rarity" in variant ? variant.rarity : base.rarity,
    })),
  ];
}

