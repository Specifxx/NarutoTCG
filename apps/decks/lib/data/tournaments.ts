import hiddenLeafScPortland from "@/data/seed/tournaments/hidden-leaf-sc-portland-2026-05.json";
import hokageCupNa from "@/data/seed/tournaments/hokage-cup-na-2026.json";
import ichirakuScToronto from "@/data/seed/tournaments/ichiraku-sc-toronto-2026-06.json";
import kiriRcLondon from "@/data/seed/tournaments/kiri-rc-london-2026.json";
