import mistVillageScManchester from "@/data/seed/tournaments/mist-village-sc-manchester-2026-07.json";
import rasenganScSydney from "@/data/seed/tournaments/rasengan-sc-sydney-2026-08.json";
import shinobiOnlineOpen3 from "@/data/seed/tournaments/shinobi-online-open-3.json";
import shinobiOnlineOpen4 from "@/data/seed/tournaments/shinobi-online-open-4.json";
import sunaRcPhoenix from "@/data/seed/tournaments/suna-rc-phoenix-2026.json";

/**
 * Seed events, generated by `scripts/generate-seed.ts` (see lib/seed). The JSON is written
 * in the canonical {@link Tournament} shape, so it is cast rather than parsed.
 */
const SEED_FILES = [
  akatsukiHideoutScAustin,
  hiddenLeafScPortland,
  hokageCupNa,
  ichirakuScToronto,
  kiriRcLondon,
  konohaRcSeattle,
  leafVillageScChicago,
  mistVillageScManchester,
  rasenganScSydney,
  shinobiOnlineOpen3,
  shinobiOnlineOpen4,
  sunaRcPhoenix,
] as unknown as Tournament[];

/** All seed tournaments, newest first. */
export const SEED_TOURNAMENTS: readonly Tournament[] = SEED_FILES.slice().sort(
  (a, b) => b.date.localeCompare(a.date) || a.id.localeCompare(b.id),
);

export function getSeedTournaments(): readonly Tournament[] {
  return SEED_TOURNAMENTS;
}

export function getTournament(id: string): Tournament | undefined {
  return SEED_TOURNAMENTS.find((t) => t.id === id);
}
